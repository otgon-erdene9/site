// ===== STATE =====
let activeFilter = 'all';
let searchQuery = '';

// ===== FILTER =====
function setFilter(cat, btn) {
  activeFilter = cat;
  document.querySelectorAll('.filter-btn').forEach(b => b.classList.remove('active'));
  btn.classList.add('active');
  applyFilters();
}

function filterRecipes() {
  searchQuery = document.getElementById('searchInput').value.toLowerCase();
  applyFilters();
}

function applyFilters() {
  const cards = document.querySelectorAll('#recipeGrid .recipe-card');
  let visible = 0;
  cards.forEach(card => {
    const cat = card.dataset.cat;
    const name = (card.dataset.name || '').toLowerCase();
    const matchCat = activeFilter === 'all' || cat === activeFilter;
    const matchSearch = !searchQuery || name.includes(searchQuery);
    if (matchCat && matchSearch) {
      card.classList.remove('hidden');
      visible++;
    } else {
      card.classList.add('hidden');
    }
  });
  document.getElementById('noResults').style.display = visible === 0 ? 'block' : 'none';
}

// ===== MODAL =====
function openModal(id) {
  const r = RECIPES[id];
  if (!r) return;

  document.getElementById('modalImg').src = r.img;
  document.getElementById('modalImg').alt = r.title;
  document.getElementById('modalTag').textContent = r.tag;
  document.getElementById('modalTitle').textContent = r.title;

  document.getElementById('modalMeta').innerHTML = `
    <span>⏱ ${r.time}</span>
    <span>👥 ${r.serves}</span>
    <span>🔥 ${r.diff}</span>
    <span>🥗 ${r.calories}</span>
  `;

  const ingList = document.getElementById('modalIngredients');
  ingList.innerHTML = r.ingredients.map(i => `<li>${i}</li>`).join('');

  const stepList = document.getElementById('modalSteps');
  stepList.innerHTML = r.steps.map((s, i) => `
    <li><span class="step-num">${i + 1}</span><span>${s}</span></li>
  `).join('');

  document.getElementById('modalTip').textContent = r.tip;

  document.getElementById('modalOverlay').classList.add('open');
  document.body.style.overflow = 'hidden';
}

function closeModal(e) {
  if (e.target === document.getElementById('modalOverlay')) closeModalDirect();
}

function closeModalDirect() {
  document.getElementById('modalOverlay').classList.remove('open');
  document.body.style.overflow = '';
}

// Close on ESC
document.addEventListener('keydown', e => {
  if (e.key === 'Escape') closeModalDirect();
});
